param([string]$Dxc='C:/Program Files (x86)/Windows Kits/10/bin/10.0.22621.0/x64/dxc.exe',[switch]$Check,[switch]$CheckSourceOnly)
$ErrorActionPreference='Stop'
$root=Split-Path -Parent $PSScriptRoot
$source=Join-Path $root 'Shaders/Private/SensorOwnedRayTracing.usf'
$target=Join-Path $root 'Source/ma0t10_dtBootstrap/Private/SensorNativeRayQueryDxil.h'
$canonical=[IO.File]::ReadAllText($source).Replace("`r`n","`n")
$sha=[Security.Cryptography.SHA256]::Create()
try{$hash=([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($canonical)))).Replace('-','').ToLowerInvariant()}finally{$sha.Dispose()}
if($CheckSourceOnly){
    if(-not ([IO.File]::ReadAllText($target).Contains("// Source SHA256: $hash;"))){throw 'Native DXIL source hash is stale; regenerate the header'}
    Write-Output "Native shader source hash matches: $hash";return
}
$folder=Join-Path $root 'Saved/Reports/LIDAR-GPU-REWRITE-26g/shader'
New-Item -ItemType Directory -Force -Path $folder|Out-Null
$binary=Join-Path $folder 'SensorInline.dxil'
& $Dxc -T cs_6_5 -E MainInlineCS -D SENSOR_NATIVE_INLINE=1 -D SENSOR_NATIVE_STANDALONE=1 -O3 -Ges -Fo $binary $source
if($LASTEXITCODE -ne 0){throw 'DXC compilation failed'}
$bytes=[IO.File]::ReadAllBytes($binary)
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by Scripts/generate_sensor_native_shader.ps1; do not edit.')
$lines.Add("// Source SHA256: $hash; DXC cs_6_5 MainInlineCS -O3 -Ges")
$lines.Add('#pragma once')
$lines.Add('static constexpr uint8 SensorNativeRayQueryDxil[] = {')
for($i=0;$i -lt $bytes.Length;$i+=16){$last=[Math]::Min($i+15,$bytes.Length-1);$lines.Add('    '+(($bytes[$i..$last]|ForEach-Object{'0x{0:x2}' -f $_}) -join ',')+',')}
$lines.Add('};')
$text=($lines -join "`r`n")+"`r`n"
if($Check){if([IO.File]::ReadAllText($target) -cne $text){throw 'Generated DXIL header differs; regenerate with the pinned Windows SDK DXC'}}
else{[IO.File]::WriteAllText($target,$text,[Text.UTF8Encoding]::new($false))}
Write-Output "Native shader: $($bytes.Length) bytes; source $hash; check=$Check"
